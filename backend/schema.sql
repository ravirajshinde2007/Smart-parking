USE defaultdb;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  first_name VARCHAR(80) NOT NULL,
  last_name VARCHAR(80) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  phone VARCHAR(30) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('USER','ADMIN','OPERATOR') NOT NULL DEFAULT 'USER',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS parking_lots (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  state VARCHAR(80) NOT NULL,
  city VARCHAR(100) NOT NULL,
  area VARCHAR(120) NOT NULL,
  locality VARCHAR(120),
  latitude DECIMAL(10,7) NOT NULL,
  longitude DECIMAL(10,7) NOT NULL,
  capacity INT UNSIGNED NOT NULL,
  rate_per_hour DECIMAL(10,2) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_city_area (city, area)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS parking_slots (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  parking_lot_id BIGINT UNSIGNED NOT NULL,
  slot_code VARCHAR(20) NOT NULL,
  slot_status ENUM('VACANT','RESERVED','OCCUPIED','MAINTENANCE') NOT NULL DEFAULT 'VACANT',
  vehicle_type ENUM('ANY','CAR','BIKE','EV') NOT NULL DEFAULT 'ANY',
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_lot_slot (parking_lot_id, slot_code),
  CONSTRAINT fk_slot_lot FOREIGN KEY (parking_lot_id) REFERENCES parking_lots(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS bookings (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  booking_code VARCHAR(30) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  parking_lot_id BIGINT UNSIGNED NOT NULL,
  parking_slot_id BIGINT UNSIGNED NOT NULL,
  vehicle_type VARCHAR(30) NOT NULL,
  car_type VARCHAR(100) NOT NULL,
  car_number VARCHAR(30) NOT NULL,
  duration_hours INT UNSIGNED NOT NULL,
  start_time DATETIME NOT NULL,
  end_time DATETIME NULL,
  amount DECIMAL(10,2) NOT NULL,
  status ENUM('RESERVED','PARKED','COMPLETED','CANCELLED','ENTRY_REVIEW','EXIT_REVIEW') NOT NULL DEFAULT 'RESERVED',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_booking_lot FOREIGN KEY (parking_lot_id) REFERENCES parking_lots(id),
  CONSTRAINT fk_booking_slot FOREIGN KEY (parking_slot_id) REFERENCES parking_slots(id),
  INDEX idx_booking_user_status (user_id, status),
  INDEX idx_booking_plate (car_number)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS payments (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  booking_id BIGINT UNSIGNED NOT NULL,
  amount DECIMAL(10,2) NOT NULL,
  method ENUM('UPI','Card','Net Banking','Cash','QR Code') NOT NULL,
  transaction_id VARCHAR(80) NOT NULL UNIQUE,
  status ENUM('PAID','PENDING','FAILED','REFUNDED') NOT NULL DEFAULT 'PAID',
  paid_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_payment_booking FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE,
  INDEX idx_payment_booking (booking_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS access_logs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  booking_id BIGINT UNSIGNED NOT NULL,
  event_type ENUM('ENTRY','EXIT') NOT NULL,
  event_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  detected_plate VARCHAR(30),
  expected_plate VARCHAR(30),
  plate_match BOOLEAN NOT NULL DEFAULT FALSE,
  ocr_confidence DECIMAL(5,2),
  photo_id BIGINT UNSIGNED NULL,
  notes VARCHAR(500),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_access_booking FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE,
  INDEX idx_access_booking (booking_id),
  INDEX idx_access_event (event_type, event_time)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS vehicle_photos (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  booking_id BIGINT UNSIGNED NOT NULL,
  access_log_id BIGINT UNSIGNED NULL,
  event_type ENUM('ENTRY','EXIT') NOT NULL,
  file_name VARCHAR(255) NOT NULL,
  file_path VARCHAR(500) NOT NULL,
  mime_type VARCHAR(80) NOT NULL,
  sha256 CHAR(64) NOT NULL,
  ocr_text VARCHAR(255),
  ocr_confidence DECIMAL(5,2),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_photo_booking FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE,
  INDEX idx_photo_booking (booking_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(160) NOT NULL,
  message VARCHAR(500) NOT NULL,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
